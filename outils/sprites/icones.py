def tout():
    """Écrit toutes les icônes, à l'échelle courante de la toile."""
    for nom, lignes in UI.items():
        t = Toile(12, 12)
        t.motif(0, 0, [l.replace("0", ".").replace("1", "#") for l in lignes], PAL)
        ecrire("ui-" + nom, t, commentaire="icône d'interface (docs/STYLE.md) : " + nom)
    for nom, (car, lignes) in SIGNES.items():
        t = Toile(7, 7)
        t.motif(0, 0, lignes, PAL)
        ecrire("signe-" + nom, t, commentaire="signe d'interface (docs/STYLE.md) : %s U+%04X" % (nom, ord(car)))
    table()


def table():
    """assets/signes.txt : caractère (code hexadécimal) → sprite du signe, lu par l'interface."""
    if toile.ECHELLE != 1:
        return
    chemin = os.path.join(os.path.dirname(toile.SORTIE), "signes.txt")
    with open(chemin, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Signes d'interface : code du caractère → sprite 7 × 7 (outils/sprites/icones.py). Ne pas éditer.\n")
        for nom, (car, _) in SIGNES.items():
            f.write("%04X signe-%s\n" % (ord(car), nom))


def planche():
    """planches/icones.png : chaque icône à 1×, à sa taille d'écran (×4) et en dessin fin, sur clair et sur sombre."""
    from PIL import Image, ImageDraw
    import rendu

    def image(lignes, z, encre, fin):
        net = [l.replace("0", ".").replace("1", "#") for l in lignes]
        if fin:
            net = rendu.agrandir_image(net, PAL)
            z //= 2
        im = Image.new("RGBA", (len(net[0]) * z, len(net) * z), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        for y, l in enumerate(net):
            for x, ch in enumerate(l):
                if ch != ".":
                    c = encre if ch == "#" else (0xf6, 0x9d, 0x50, 255)
                    d.rectangle([x * z, y * z, x * z + z - 1, y * z + z - 1], fill=c)
        return im

    themes = [((0xfb, 0xf3, 0xe4), (0x1c, 0x21, 0x28, 255), (0x57, 0x60, 0x6a)),
              ((0x15, 0x1a, 0x2e), (0xe6, 0xec, 0xf2, 255), (0xad, 0xba, 0xc7))]
    cases = [("ui-" + n, l) for n, l in UI.items()] + [("signe-" + n, l) for n, (_, l) in SIGNES.items()]
    col, cw, ch = 9, 132, 96
    rangs = (len(cases) + col - 1) // col
    W, H = col * cw, rangs * ch
    out = Image.new("RGBA", (W, H * 2), (0, 0, 0, 255))
    d = ImageDraw.Draw(out)
    for k, (fond, encre, pale) in enumerate(themes):
        d.rectangle([0, k * H, W, (k + 1) * H], fill=fond + (255,))
        for i, (nom, lignes) in enumerate(cases):
            x, y = (i % col) * cw + 8, k * H + (i // col) * ch + 8
            a = image(lignes, 1, encre, False)
            b = image(lignes, 4, encre, False)
            c = image(lignes, 4, encre, True)
            out.alpha_composite(a, (x, y + 24))
            out.alpha_composite(b, (x + 18, y))
            out.alpha_composite(c, (x + 18 + b.width + 8, y))
            d.text((x, y + 62), nom, fill=pale)
    dossier = os.path.join(os.path.dirname(os.path.abspath(__file__)), "planches")
    os.makedirs(dossier, exist_ok=True)
    chemin = os.path.join(dossier, "icones.png")
    out.save(chemin)
    print(chemin, out.size)


if __name__ == "__main__":
    planche()
