    public static int[,] Texte(string texte)
    {
        var glyphes = texte.Select(c => Glyphes.TryGetValue(c, out var g) ? g : Glyphes[' ']).ToList();
        int largeur = glyphes.Sum(g => g[0].Length) + Math.Max(0, glyphes.Count - 1);
        var m = new int[5, largeur];
        int x = 0;
        foreach (var g in glyphes)
        {
            for (int r = 0; r < 5; r++)
            for (int c = 0; c < g[r].Length; c++)
                m[r, x + c] = g[r][c] == '1' ? 1 : 0;
            x += g[0].Length + 1;
        }
        return m;
    }

    // Le caractère a-t-il un dessin ?
    public static bool Connu(char c) => Glyphes.ContainsKey(c);
